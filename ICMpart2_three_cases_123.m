function err = powerResidual(V,Y,S)
    mismatch = V.*conj(Y*V)-S;
    err = max([abs(real(mismatch(2:end)));abs(imag(mismatch(2:end)))]);
end

function out = solveConventional(method,V,Y,S,tol,maxUpdates)
    n = numel(V); m = n-1;
    Yll = Y(2:end,2:end);
    history = nan(maxUpdates+1,1);
    voltageHistory = nan(m,maxUpdates+1);
    converged = false;
    for k = 0:maxUpdates
        voltageHistory(:,k+1) = abs(V(2:end));
        history(k+1) = powerResidual(V,Y,S);
        if history(k+1) <= tol
            converged = true; break;
        end
        if ~isfinite(history(k+1))
            break;
        end
        if k == maxUpdates, break; end
        if strcmp(method,'current')
            % Complex current-mismatch Newton:
            % F = Y_LL*V + Y_L0 - conj(S./V).
            v = V(2:end);
            F = (Y*V); F = F(2:end)-conj(S(2:end)./v);
            C = diag(conj(S(2:end))./conj(v).^2);
            J = [Yll,C;conj(C),conj(Yll)];
            step = J\[F;conj(F)];
            V(2:end) = v-step(1:m);
        else
            % Polar Newton: J=[H N; M L], z_{k+1}=z_k-J\F.
    % The mismatch is formed from the original AC P/Q equations.
            Vm = abs(V); theta = angle(V); delta = theta-theta.';
            G = real(Y); B = imag(Y); Scalc = V.*conj(Y*V);
            P = real(Scalc); Q = imag(Scalc);
            diagidx = 1:n+1:n*n;
            H = (Vm*Vm.').*(G.*sin(delta)-B.*cos(delta));
            H(diagidx) = -Q-diag(B).*Vm.^2;
            N = Vm.*(G.*cos(delta)+B.*sin(delta));
            N(diagidx) = P./Vm+diag(G).*Vm;
            M = -(Vm*Vm.').*(G.*cos(delta)+B.*sin(delta));
            M(diagidx) = P-diag(G).*Vm.^2;
            K = Vm.*(G.*sin(delta)-B.*cos(delta));
            K(diagidx) = Q./Vm-diag(B).*Vm;
            ii = 2:n;
            J = [H(ii,ii),N(ii,ii);M(ii,ii),K(ii,ii)];
            step = J\[P(ii)-real(S(ii));Q(ii)-imag(S(ii))];
            theta(ii) = theta(ii)-step(1:m);
            Vm(ii) = Vm(ii)-step(m+1:end);
            % Full Newton step; no damping or step rejection.
            V = Vm.*exp(1i*theta);
        end
    end
    out = struct('V',V,'history',history(1:k+1),'updates',k, ...
        'converged',converged,'voltageHistory',voltageHistory(:,1:k+1));
end

function out = solveICM(parent,r,x,S,Y,tol,maxUpdates)
    % Case 3 ICM: logarithmic-current mapping (65)-(67), Theorem 3.
    % Mapping: f(x)=log(d)-log(h(x)); Newton update:
    % x_{k+1}=x_k+(I-f_x(x_k))\(f(x_k)-x_k).
    % T=A^{-1}; each column identifies the path from the slack bus.
    n = numel(parent); m = n-1; T = eye(m);
    for child = 2:n
        p = parent(child); visited = 0;
        while p > 1
            T(p-1,child-1) = 1;
            p = parent(p); visited = visited+1;
            assert(visited < n,'Network must be a tree rooted at bus 1.');
        end
        assert(p == 1,'Network must be connected to slack bus 1.');
    end
    U = T*real(S(2:end)); Z = T*imag(S(2:end));
    R = (T-eye(m)).*r.'; X = (T-eye(m)).*x.';
    d = 1+2*T.'*(r.*U+x.*Z);
    W = T.'*((r.*(2*T-eye(m))).*r.'+(x.*(2*T-eye(m))).*x.');
    c = U.^2+Z.^2;
    K = -2*(U.*R+Z.*X);
    assert(all(d>0) && all(c>0) && all(K(:)>=-1e-12) && all(W(:)>0), ...
        'The sufficient conditions for the ICM theorem are not met.');
    state = (1+max(abs(log(d)-log(c))))*ones(m,1);
    history = nan(maxUpdates+1,1); mapHistory = history;
    states = nan(m,maxUpdates+1); voltages = nan(n,maxUpdates+1);
    converged = false;
    for k = 0:maxUpdates
        states(:,k+1) = state;
        ell = exp(-state); P = U-R*ell; Q = Z-X*ell; We = W*ell;
        h = P.^2+Q.^2+ell.*We;
        assert(all(h>0),'Invalid logarithm argument.');
        f = log(d)-log(h);
        Jf = ((-2*P.*R-2*Q.*X+diag(We)+ell.*W).*ell.')./h;
        V = recoverVoltage(parent,r,x,d,W,R,X,U,Z,state);
        voltages(:,k+1) = abs(V);
        history(k+1) = powerResidual(V,Y,S);
        mapHistory(k+1) = max(abs(state-f));
        if history(k+1) <= tol && mapHistory(k+1) <= tol
            converged = true; break;
        end
        if k == maxUpdates, break; end
        state = state+(eye(m)-Jf)\(f-state);
    end
    states = states(:,1:k+1); voltages = voltages(:,1:k+1);
    changes = diff(states,1,2);
    out = struct('V',V,'history',history(1:k+1),'updates',k, ...
        'converged',converged,'states',states,'voltages',voltages, ...
        'mapHistory',mapHistory(1:k+1), ...
        'maxStateIncrease',max(changes(:)));
end

function V = recoverVoltage(parent,r,x,d,W,R,X,U,Z,state)
    n = numel(parent); ell = exp(-state); e2 = d-W*ell;
    assert(all(e2>0),'Reconstructed squared voltage is not positive.');
    P = U-R*ell; Q = Z-X*ell;
    delta = atan2(x.*P-r.*Q,e2-r.*P-x.*Q);
    theta = zeros(n,1); known = false(n,1); known(1) = true;
    while ~all(known)
        progressed = false;
        for j = 2:n
            if ~known(j) && known(parent(j))
                theta(j) = theta(parent(j))+delta(j-1);
                known(j) = true; progressed = true;
            end
        end
        assert(progressed,'Network is not a connected rooted tree.');
    end
    V = [1;sqrt(e2)].*exp(1i*theta);
end

function out = auditPVSolve(net,kind,tol,maxiter)
    % Cases 1-2 ICM: squared-voltage maps (15) and (30);
    % Jacobians (18) and (49), with the Newton steps in Theorems 1 and 2.
    a = auditPVModel(net,kind);
    state = auditPVInitial(a);
    history = nan(maxiter+1,1); mapHistory = history;
    states = nan(a.nl,maxiter+1); voltages = nan(a.n,maxiter+1);
    converged = false;
    for k = 0:maxiter
        [f,J,V] = auditPVQuantities(a,state);
        states(:,k+1) = state; voltages(:,k+1) = abs(V);
        history(k+1) = auditPVResidual(a,V);
        mapHistory(k+1) = max(abs(state-f));
        if history(k+1)<=tol && mapHistory(k+1)<=tol
            converged = true; break;
        end
        if k==maxiter, break; end
        state = state+(eye(a.nl)-J)\(f-state);
    end
    states = states(:,1:k+1); voltages = voltages(:,1:k+1);
    differences = diff(states,1,2);
    out = struct('V',V,'iterations',k,'history',history(1:k+1), ...
        'map_history',mapHistory(1:k+1),'states',states,'voltages',voltages, ...
        'converged',converged,'monotone',all(differences(:)<=1e-10), ...
        'max_state_increase',max(differences(:)));
end

function out = auditPVPolar(net,V0,tol,maxiter)
    % Polar Newton for PV-PQ systems; the Jacobian follows the
    % standard [H N; M L] formulation of the AC power-flow equations.
    if max(abs(net.r))<1e-13, kind='lossless'; else, kind='uniform'; end
    a = auditPVModel(net,kind); V = V0(:);
    V(1) = a.vset(1)*exp(1i*angle(V(1)));
    V(a.pv) = a.vset(a.pv).*exp(1i*angle(V(a.pv)));
    history = nan(maxiter+1,1);
    voltageHistory = nan(numel(a.pq),maxiter+1);
    converged = false;
    for k = 0:maxiter
        voltageHistory(:,k+1) = abs(V(a.pq));
        history(k+1) = auditPVResidual(a,V);
        if history(k+1)<=tol
            converged = true; break;
        end
        if k==maxiter, break; end
        if ~isfinite(history(k+1)), break; end
        E = abs(V); theta = angle(V); delta = theta-theta.';
        G = real(a.Y); B = imag(a.Y); S = V.*conj(a.Y*V);
        P = real(S); Q = imag(S); dd = 1:a.n+1:a.n*a.n;
        H = (E*E.').*(G.*sin(delta)-B.*cos(delta));
        H(dd) = -Q-diag(B).*E.^2;
        N = E.*(G.*cos(delta)+B.*sin(delta));
        N(dd) = P./E+diag(G).*E;
        M = -(E*E.').*(G.*cos(delta)+B.*sin(delta));
        M(dd) = P-diag(G).*E.^2;
        K = E.*(G.*sin(delta)-B.*cos(delta));
        K(dd) = Q./E-diag(B).*E;
        ii = 2:a.n;
        J = [H(ii,ii),N(ii,a.pq);M(a.pq,ii),K(a.pq,a.pq)];
        F = [P(ii)-a.p(ii);Q(a.pq)-a.q(a.pq)];
        step = J\F;
        theta(ii) = theta(ii)-step(1:a.m);
        E(a.pq) = E(a.pq)-step(a.m+1:end);
        % Retain the full Newton step, including negative trial magnitudes.
        V = E.*exp(1i*theta);
    end
    out = struct('V',V,'iterations',k,'history',history(1:k+1), ...
        'converged',converged,'voltageHistory',voltageHistory(:,1:k+1));
end

function Vdc = auditPVDC(net)
    % Classical DC start: Bred*theta=P; voltage magnitudes are set to 1 p.u.
    n = numel(net.parent); parent = net.parent(:); x = net.x(:);
    L = zeros(n);
    for j = 2:n
        ii = [parent(j),j]; L(ii,ii) = L(ii,ii)+[1,-1;-1,1]/x(j-1);
    end
    p = net.p(:); theta = [0;L(2:end,2:end)\p(2:end)];
    E = ones(n,1); E(1)=net.vset(1); E(net.pv)=net.vset(net.pv);
    Vdc = E.*exp(1i*theta);
end

function a = auditPVModel(net,kind)
    a.parent = net.parent(:); a.r = net.r(:); a.x = net.x(:);
    a.p = net.p(:); a.q = net.q(:); a.vset = net.vset(:);
    a.pv = net.pv(:); a.n = numel(a.parent); a.m = a.n-1;
    a.pq = setdiff((2:a.n)',a.pv); a.nl = numel(a.pq); a.kind=kind;
    assert(a.parent(1)==0,'parent(1) must be zero; other parents use one-based IDs.');
    assert(all(a.x>0) && all(a.r>=0),'Invalid series impedances.');
    if strcmp(kind,'lossless')
        assert(max(abs(a.r))<1e-13,'Lossless case requires r=0.'); a.k=0;
    else
        a.k=mean(a.r./a.x);
        assert(max(abs(a.r./a.x-a.k))<1e-10,'R/X ratios are not uniform.');
    end
    a.b = a.x./(a.r.^2+a.x.^2);
    a.Y = complex(zeros(a.n)); a.A=eye(a.m); a.T=eye(a.m);
    for j = 2:a.n
        i = a.parent(j); ii=[i,j];
        a.Y(ii,ii)=a.Y(ii,ii)+[1,-1;-1,1]/complex(a.r(j-1),a.x(j-1));
        if i>1, a.A(i-1,j-1)=-1; end
        count=0;
        while i>1
            a.T(i-1,j-1)=1; i=a.parent(i); count=count+1;
            assert(count<a.n,'Parent array contains a cycle.');
        end
    end
    a.AL=a.A(a.pq-1,:); a.AG=a.A(a.pv-1,:); a.B=abs(a.AL);
    a.D=a.B*a.b; a.L=(a.AL.*a.b.')*a.AL.';
    a.qt=(a.q(a.pq)+a.k*a.p(a.pq))/(1+a.k^2);
    cross=(a.AL.*a.b.')*a.AG.';
    a.u=a.vset(1)^2+a.L\(2*a.qt-cross*(a.vset(a.pv).^2-a.vset(1)^2));
    a.W=(a.T-eye(a.m))*a.AG.';
    uf=a.vset(2:end).^2; uf(a.pq-1)=a.u;
    upperS=a.T*a.p(2:end)-a.k/2*a.b.*(a.A.'*(uf-a.vset(1)^2));
    criterion=a.k*upperS.*a.W;
    a.gamma=a.p(a.pv)-a.k*a.b(a.pv-1).*a.vset(a.pv).^2;
    isPQ=false(a.n,1); isPQ(a.pq)=true;
    children=accumarray(a.parent(2:end),ones(a.m,1),[a.n,1]);
    pvLeaves=all(children(a.pv)==0 & isPQ(a.parent(a.pv)));
    seen=false(a.n,1); seen(a.pq(1))=true;
    for pass=1:a.n
        old=sum(seen);
        for j=a.pq.'
            i=a.parent(j);
            if isPQ(i) && (seen(i)||seen(j)), seen([i,j])=true; end
        end
        if sum(seen)==old, break; end
    end
    eachBranchPQ=all(isPQ(2:end)|isPQ(a.parent(2:end)));
    criterionMax=max([0;criterion(:)]);
    theorem38=criterionMax<=1e-11*max([1;abs(criterion(:))]);
    applicable=sum(seen)==a.nl && eachBranchPQ && ...
        (strcmp(kind,'lossless') || (pvLeaves && theorem38));
    assert(applicable,'The selected squared-voltage ICM conditions fail.');
end

function err = auditPVResidual(a,V)
    S=V.*conj(a.Y*V);
    err=max(abs([real(S(2:end))-a.p(2:end);imag(S(a.pq))-a.q(a.pq); ...
        abs(V(a.pv)).^2-a.vset(a.pv).^2]));
end

function [f,J,V] = auditPVQuantities(a,state)
    % Evaluate the squared-voltage ICM map and its Jacobian, then recover V.
    assert(all(state>0),'Nonpositive squared PQ voltage.');
    squared=a.vset.^2; squared(a.pq)=state;
    product=squared(2:end).*squared(a.parent(2:end)); w=[];
    if strcmp(a.kind,'lossless')
        S=a.T*a.p(2:end);
    else
        assert(all(state-a.u<=1e-10*max(1,abs(a.u))),'State exceeds u.');
        w=(1+a.k^2)*a.b(a.pv-1).^2.*a.vset(a.pv).^2.* ...
            squared(a.parent(a.pv))-a.gamma.^2;
        assert(all(w>0),'PV discriminant is not strictly positive.');
        Cg=(-a.k*a.gamma+sqrt(w))/(1+a.k^2);
        assert(all(Cg>0),'Selected PV cosine is not positive.');
        rhs=zeros(a.m,1);
        rhs(a.pq-1)=(a.p(a.pq)-a.k*a.q(a.pq))/(1+a.k^2);
        rhs(a.pv-1)=(a.gamma+a.k*sqrt(w))/(1+a.k^2);
        S=a.T*rhs;
    end
    radicand=a.b.^2.*product-S.^2;
    assert(all(radicand>0),'Branch cosine radicand is not strictly positive.');
    C=sqrt(radicand);
    if strcmp(a.kind,'uniform'), C(a.pv-1)=Cg; end
    f=(a.qt+a.B*C)./a.D;
    % Paper Eq49; independent of direct square-root derivative implementation.
    M=diag(C)+a.k*S.*(a.T*a.AG.'*a.AG);
    right=(0.5*(a.b.^2.*product).*a.B.')./state.';
    Cx=M\right; J=(a.B*Cx)./a.D;
    delta=atan2(S,C); theta=zeros(a.n,1); known=false(a.n,1);known(1)=true;
    while ~all(known)
        progress=false;
        for j=2:a.n
            if ~known(j) && known(a.parent(j))
                theta(j)=theta(a.parent(j))+delta(j-1);known(j)=true;progress=true;
            end
        end
        assert(progress,'Parent array is not a connected tree.');
    end
    V=sqrt(squared).*exp(1i*theta);
end

function state = auditPVInitial(a)
    % Theorem 1 upper bound for Case 1; equation (34) for Case 2.
    if strcmp(a.kind,'uniform')
        state=a.u; return;
    end
    v=a.L\ones(a.nl,1);direction=v/max(v);
    scale=max(max(a.vset([1;a.pv])),max(sqrt(max(a.u,0))./direction))*(1+1e-8);
    safe=scale;previous=scale;
    for doublings=0:79
        if auditPVIsUpper(a,(scale*direction).^2)
            low=max(previous,safe);high=scale;
            if high>low
                for iter=1:24
                    middle=(low+high)/2;
                    if auditPVIsUpper(a,(middle*direction).^2), high=middle; else, low=middle; end
                end
                scale=high*(1+1e-7);
            end
            state=(scale*direction).^2;
            return;
        end
        previous=scale;scale=2*scale;
    end
    error('Failed to construct theorem1 upper initialization.');
end

function yes = auditPVIsUpper(a,state)
    try
        [f,~,~]=auditPVQuantities(a,state);
        yes=all(state-f>1e-12*max(1,state));
    catch
        yes=false;
    end
end
